local T = require("testlib")
local Stubs = require("wow_stubs")
local describe, it = T.describe, T.it

describe("ns.Later", function()
    it("runs on the next frame, not right away", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        local ran = 0
        ns.Later("test", function() ran = ran + 1 end)
        T.eq(ran, 0)
        Stubs.RunTimers()
        T.eq(ran, 1)
    end)

    it("runs a key once, with the latest function, however often it was asked for", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        local result = {}
        ns.Later("test", function() result[#result + 1] = "first" end)
        ns.Later("test", function() result[#result + 1] = "second" end)
        ns.Later("other", function() result[#result + 1] = "other" end)
        Stubs.RunTimers()
        table.sort(result)
        T.same(result, { "other", "second" })
    end)

    it("runs a request made while the others run on the next frame, never in the same one", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        -- A change that makes the game fire an event that asks for the change again.
        local ran = 0
        local function again()
            ran = ran + 1
            ns.Later("test", again)
        end
        ns.Later("test", again)
        Stubs.NextFrame()
        T.eq(ran, 1)
        Stubs.NextFrame()
        T.eq(ran, 2)
    end)

    it("waits for the end of combat", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        local ran = 0
        Stubs.SetCombat(true)
        ns.Later("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        T.eq(ran, 0)
        Stubs.SetCombat(false)
        Stubs.RunTimers()
        T.eq(ran, 1)
    end)

    it("runs in combat when the change is allowed there", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        local ran = 0
        Stubs.SetCombat(true)
        ns.Later("test", function() ran = ran + 1 end, true)
        Stubs.RunTimers()
        T.eq(ran, 1)
        -- The next request for the same key waits again unless it says otherwise.
        ns.Later("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        T.eq(ran, 1)
        Stubs.SetCombat(false)
        Stubs.RunTimers()
        T.eq(ran, 2)
    end)

    -- The game froze on closing its settings in the controller interface after changes made while
    -- they were open.
    it("waits in the controller interface until the settings and the game menu are closed", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        SettingsPanel:Show()
        Stubs.SetControllerWindow(SettingsPanel)
        local ran = 0
        ns.Later("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        Stubs.AdvanceTime()
        T.eq(ran, 0)
        -- Closing the settings goes back to the game menu.
        SettingsPanel:Hide()
        GameMenuFrame:Show()
        Stubs.SetControllerWindow(GameMenuFrame)
        Stubs.AdvanceTime()
        Stubs.AdvanceTime()
        T.eq(ran, 0)
        GameMenuFrame:Hide()
        Stubs.SetControllerWindow(nil)
        Stubs.RunTimers()
        Stubs.AdvanceTime()
        T.eq(ran, 0) -- not right after it closed
        Stubs.AdvanceTime()
        T.eq(ran, 1)
    end)

    it("waits for the settings in combat too, when the change is allowed there", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        Stubs.SetCombat(true)
        SettingsPanel:Show()
        Stubs.SetControllerWindow(SettingsPanel)
        local ran = 0
        ns.Later("test", function() ran = ran + 1 end, true)
        Stubs.RunTimers()
        T.eq(ran, 0)
        SettingsPanel:Hide()
        Stubs.SetControllerWindow(nil)
        Stubs.AdvanceTime()
        Stubs.AdvanceTime()
        T.eq(ran, 1)
    end)

    it("runs right away with the settings open, without the controller interface", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        SettingsPanel:Show()
        Stubs.SetControllerWindow(SettingsPanel)
        local ran = 0
        ns.Later("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        T.eq(ran, 1)
    end)
end)

describe("ns.LaterOutsideWindows", function()
    -- A window of the game that has the controller, like the settings.
    local function openWindow()
        local window = _G.CreateFrame("Frame", nil, _G.UIParent)
        window:Show()
        Stubs.SetControllerWindow(window)
        return window
    end

    it("runs on the next frame without the controller interface, whatever window is open", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        openWindow()
        local ran = 0
        ns.LaterOutsideWindows("test", function() ran = ran + 1 end)
        T.eq(ran, 0)
        Stubs.RunTimers()
        T.eq(ran, 1)
    end)

    it("waits until no window has the controller, then runs once", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        openWindow()
        local ran = 0
        ns.LaterOutsideWindows("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        Stubs.AdvanceTime()
        Stubs.AdvanceTime()
        T.eq(ran, 0)
        Stubs.SetControllerWindow(nil)
        Stubs.RunTimers()
        T.eq(ran, 0) -- not right after the window closed
        Stubs.AdvanceTime()
        T.eq(ran, 0) -- nor at the first check without it
        Stubs.AdvanceTime()
        T.eq(ran, 1)
        Stubs.AdvanceTime()
        T.eq(ran, 1)
    end)

    it("runs at the next check in the controller interface, with no window or a hidden one", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        local ran = 0
        ns.LaterOutsideWindows("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        T.eq(ran, 0)
        Stubs.AdvanceTime()
        T.eq(ran, 1)
        -- The game may still name a window it has hidden.
        openWindow():Hide()
        ns.LaterOutsideWindows("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        Stubs.AdvanceTime()
        T.eq(ran, 2)
    end)

    it("runs the latest request for a key that waited", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        openWindow()
        local result = {}
        ns.LaterOutsideWindows("test", function() result[#result + 1] = "first" end)
        Stubs.RunTimers()
        ns.LaterOutsideWindows("test", function() result[#result + 1] = "second" end)
        Stubs.RunTimers()
        Stubs.SetControllerWindow(nil)
        Stubs.AdvanceTime()
        Stubs.AdvanceTime()
        T.same(result, { "second" })
    end)

    it("leaves the other requests alone", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        openWindow()
        local ran = 0
        ns.Later("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        T.eq(ran, 1)
    end)

    it("waits for the end of combat too", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        local ran = 0
        Stubs.SetCombat(true)
        ns.LaterOutsideWindows("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        T.eq(ran, 0)
        openWindow()
        Stubs.SetCombat(false)
        Stubs.RunTimers()
        T.eq(ran, 0)
        Stubs.SetControllerWindow(nil)
        Stubs.AdvanceTime()
        Stubs.AdvanceTime()
        T.eq(ran, 1)
    end)

    it("checks for a window again when combat ended after the check let it go", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        Stubs.SetControllerUI(true)
        local ran = 0
        ns.LaterOutsideWindows("test", function() ran = ran + 1 end)
        Stubs.RunTimers()
        Stubs.SetCombat(true)
        Stubs.AdvanceTime()
        T.eq(ran, 0)
        openWindow()
        Stubs.SetCombat(false)
        Stubs.RunTimers()
        Stubs.AdvanceTime()
        T.eq(ran, 0)
        Stubs.SetControllerWindow(nil)
        Stubs.AdvanceTime()
        Stubs.AdvanceTime()
        T.eq(ran, 1)
    end)
end)
