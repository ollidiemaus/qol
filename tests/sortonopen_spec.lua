local T = require("testlib")
local Stubs = require("wow_stubs")
local describe, it = T.describe, T.it

local function start(savedOptions, options)
    local ns = Stubs.LoadAddon(options)
    Stubs.Login(savedOptions)
    return ns
end

-- How many sorts the game was asked for, once what an open started has run.
local function sorts()
    Stubs.RunTimers()
    return Stubs.state().sorts
end

describe("sort on open", function()
    it("sorts when the player opens the combined bag", function()
        start({ sortOnOpen = true })
        ToggleAllBags()
        T.eq(sorts(), 1)
    end)

    it("is off by default", function()
        start()
        ToggleAllBags()
        T.eq(sorts(), 0)
    end)

    it("applies a change of the option from the next open, without a reload", function()
        local ns = start()
        ToggleAllBags()
        T.eq(sorts(), 0)
        ToggleAllBags()
        ns.Options:Set("sortOnOpen", true)
        ToggleAllBags()
        T.eq(sorts(), 1)
        ToggleAllBags()
        ns.Options:Set("sortOnOpen", false)
        ToggleAllBags()
        T.eq(sorts(), 1)
    end)

    it("doesn't sort in combat, not even when combat ends, and sorts on the next open after it", function()
        start({ sortOnOpen = true })
        Stubs.SetCombat(true)
        ToggleAllBags()
        T.eq(sorts(), 0)
        Stubs.SetCombat(false)
        T.eq(sorts(), 0, "no catch-up")
        ToggleAllBags()
        ToggleAllBags()
        T.eq(sorts(), 1)
    end)

    it("sorts with the controller interface on, and after a switch to it and back", function()
        start({ sortOnOpen = true })
        Stubs.SetControllerUI(true)
        ToggleAllBags()
        T.eq(sorts(), 1)
        ToggleAllBags()
        Stubs.SetControllerUI(false)
        ToggleAllBags()
        T.eq(sorts(), 2)
    end)

    it("sorts when the player opens separate bags, once for several at once", function()
        start({ sortOnOpen = true })
        Stubs.SetSeparateBags(true)
        ToggleAllBags()
        T.eq(sorts(), 1)
    end)

    it("sorts when the player opens any one of the bags they carry, on its own", function()
        start({ sortOnOpen = true })
        Stubs.SetSeparateBags(true)
        for bagID = 0, 5 do
            ToggleBag(bagID)
            T.eq(sorts(), bagID + 1)
            ToggleBag(bagID)
        end
    end)

    it("doesn't sort for the keyring or a bank bag", function()
        start({ sortOnOpen = true })
        ToggleBag(-1)
        ToggleBag(6)
        T.eq(sorts(), 0)
        Stubs.SetSeparateBags(true)
        ToggleBag(-1)
        ToggleBag(6)
        T.eq(sorts(), 0)
    end)

    it("doesn't sort when the game opens the bags, and sorts on the player's next open", function()
        start({ sortOnOpen = true })
        OpenAllBags()
        T.eq(sorts(), 0)
        ToggleAllBags()
        ToggleAllBags()
        T.eq(sorts(), 1)
    end)

    it("doesn't sort when the game opens separate bags", function()
        start({ sortOnOpen = true })
        Stubs.SetSeparateBags(true)
        OpenAllBags()
        T.eq(sorts(), 0)
    end)

    it("sorts on the player's next open after the game was refused a bag already open", function()
        start({ sortOnOpen = true })
        ToggleAllBags()
        T.eq(sorts(), 1)
        OpenAllBags()
        T.eq(sorts(), 1)
        ToggleAllBags()
        ToggleAllBags()
        T.eq(sorts(), 2)
    end)

    it("doesn't sort when the game opens only the bags with an item that fits", function()
        start({ sortOnOpen = true }, { client = "retail" })
        OpenAllBagsMatchingContext()
        T.eq(sorts(), 0)
        ToggleAllBags()
        ToggleAllBags()
        T.eq(sorts(), 1)
    end)
end)
