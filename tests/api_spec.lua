local T = require("testlib")
local Stubs = require("wow_stubs")
local describe, it = T.describe, T.it

describe("public API", function()
    it("is exposed as a global", function()
        local ns = Stubs.LoadAddon()
        T.eq(QoLAPI, ns.API)
    end)

    it("switches the viewport through the same path as the settings page", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        T.eq(QoLAPI.IsFeatureEnabled("viewport"), false)
        T.eq(QoLAPI.SetFeatureEnabled("viewport", true), true)
        T.eq(ns.Options:Get("viewportEnabled"), true)
        T.eq(QoLAPI.IsFeatureEnabled("Viewport"), true)
        QoLAPI.SetFeatureEnabled("viewport", false)
        T.eq(ns.Options:Get("viewportEnabled"), false)
    end)

    it("switches click casting", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        T.eq(QoLAPI.IsFeatureEnabled("clickCast"), false)
        T.eq(QoLAPI.SetFeatureEnabled("clickcast", true), true)
        T.eq(ns.Options:Get("clickCast"), true)
        QoLAPI.SetFeatureEnabled("clickCast", false)
        T.eq(ns.Options:Get("clickCast"), false)
    end)

    it("switches tracked buffs on the group frames, leaving the game's buffs setting alone", function()
        local ns = Stubs.LoadAddon()
        Stubs.Login()
        local sets = #Stubs.state().cvarSets
        T.eq(QoLAPI.IsFeatureEnabled("groupframes"), false)
        T.eq(QoLAPI.SetFeatureEnabled("groupFrames", true), true)
        T.eq(ns.Options:Get("groupFrameBuffs"), true)
        QoLAPI.SetFeatureEnabled("groupframes", false)
        T.eq(ns.Options:Get("groupFrameBuffs"), false)
        T.eq(#Stubs.state().cvarSets, sets, "no game setting written")
        T.eq(Stubs.state().cvars.raidFramesDisplayBuffs, "1")
    end)

    it("lists its features", function()
        Stubs.LoadAddon()
        T.eq(table.concat(QoLAPI.GetFeatureNames(), ","), "clickcast,groupframes,viewport")
    end)

    it("rejects unknown features", function()
        Stubs.LoadAddon()
        Stubs.Login()
        T.eq(QoLAPI.IsFeatureEnabled("nope"), nil)
        T.eq(QoLAPI.SetFeatureEnabled("nope", true), false)
    end)
end)
